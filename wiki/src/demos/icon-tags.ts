const CATEGORIES: Record<string, string> = {
  social: "social network brand logo",
  crypto: "crypto coin token blockchain chain currency",
}

/** Everything the search matches for one icon, as lower-case words: its name, label and tags. */
export function iconSearchWords(icon: { name: string; label?: string; category?: string }) {
  const parts = Object.keys(PARTS).filter((part) => `-${icon.name}-`.includes(`-${part}-`))
  const text = [icon.name, icon.label ?? "", icon.category ? CATEGORIES[icon.category] : "", NAMES[icon.name] ?? "", ...parts.map((part) => PARTS[part])].join(" ")
  return [...new Set(text.toLowerCase().split(/[\s-]+/).filter(Boolean))]
}

/** True when every word of the query starts a word of the icon's: "del" finds trash, and "ai" does not find "mail". */
export function matchesIcon(words: string[], query: string) {
  return query.toLowerCase().split(/[\s-]+/).filter(Boolean).every((q) => words.some((word) => word.startsWith(q)))
}

/** True when the icon has tags of its own or from a word in its name. For checking coverage. */
export function hasIconTags(name: string) {
  return Boolean(NAMES[name]) || Object.keys(PARTS).some((part) => `-${name}-`.includes(`-${part}-`))
}
